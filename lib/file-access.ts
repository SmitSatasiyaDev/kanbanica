import { eq } from "drizzle-orm";
import {
  channelMessageAttachment,
  list,
  task,
  taskAttachment,
  workspace,
} from "@/db/schema";
import { db } from "@/lib/db";
import {
  getAccessibleSpaceIds,
  getWorkspaceMembership,
} from "@/lib/permissions";

// Decides whether a signed-in user may read a stored file. The file route used
// to stream any key to any session, so this is the single place that maps a
// storage key back to the workspace data it belongs to.
//
// The workspace and space are always taken from the database row, never parsed
// out of the key, because the key is user-influenced text. The one exception is
// channel files, where the row has no workspace column; those keys are always
// generated by the server (channels/{workspaceId}/{id}.{ext}).

function isSafeKey(key: string): boolean {
  if (!key || key.startsWith("/") || key.includes("\\") || key.includes("..")) {
    return false;
  }
  return key.split("/").every((segment) => segment.length > 0);
}

async function canReadTaskAttachment(
  userId: string,
  key: string
): Promise<boolean> {
  const [row] = await db
    .select({
      workspaceId: task.workspaceId,
      taskSpaceId: task.spaceId,
      listSpaceId: list.spaceId,
      deletedAt: task.deletedAt,
      workspaceStatus: workspace.status,
    })
    .from(taskAttachment)
    .innerJoin(task, eq(taskAttachment.taskId, task.id))
    .innerJoin(workspace, eq(task.workspaceId, workspace.id))
    .leftJoin(list, eq(task.listId, list.id))
    .where(eq(taskAttachment.fileUrl, key))
    .limit(1);

  if (row?.workspaceStatus !== "ACTIVE") {
    return false;
  }
  const spaceId = row.listSpaceId ?? row.taskSpaceId;
  if (!spaceId) {
    return false;
  }

  // Files on a trashed task are only reachable from the Trash, which is
  // limited to workspace Owners and Admins.
  if (row.deletedAt) {
    const membership = await getWorkspaceMembership(userId, row.workspaceId);
    return membership?.role === "OWNER" || membership?.role === "ADMIN";
  }

  // Archived projects stay viewable, so check both the active and the
  // archived list of spaces the user can see.
  const [active, archived] = await Promise.all([
    getAccessibleSpaceIds(userId, row.workspaceId),
    getAccessibleSpaceIds(userId, row.workspaceId, true),
  ]);
  return active.includes(spaceId) || archived.includes(spaceId);
}

async function canReadChannelFile(
  userId: string,
  key: string
): Promise<boolean> {
  const workspaceId = key.split("/")[1];
  if (!workspaceId) {
    return false;
  }

  const [attachment] = await db
    .select({ id: channelMessageAttachment.id })
    .from(channelMessageAttachment)
    .where(eq(channelMessageAttachment.fileUrl, key))
    .limit(1);
  if (!attachment) {
    return false;
  }

  const [ws] = await db
    .select({ status: workspace.status })
    .from(workspace)
    .where(eq(workspace.id, workspaceId))
    .limit(1);
  if (ws?.status !== "ACTIVE") {
    return false;
  }

  const membership = await getWorkspaceMembership(userId, workspaceId);
  return membership !== null;
}

export async function canReadStoredFile(
  userId: string,
  key: string
): Promise<boolean> {
  if (!isSafeKey(key)) {
    return false;
  }

  const prefix = key.split("/")[0];
  switch (prefix) {
    case "avatars":
      // Avatars show up across workspaces (mentions, member lists), so any
      // signed-in user may read them.
      return true;
    case "attachments":
      return canReadTaskAttachment(userId, key);
    case "channels":
      return canReadChannelFile(userId, key);
    default:
      return false;
  }
}
